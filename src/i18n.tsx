const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, fa };

export type Translate = (key: TranslationKey, vars?: Record<string, string | number>) => string;

function makeTranslate(language: Language): Translate {
  return (key, vars) => {
    const template = dictionaries[language][key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, name: string) =>
      name in vars ? String(vars[name]) : `{${name}}`,
    );
  };
}

interface I18nValue {
  lang: Language;
  dir: 'rtl' | 'ltr';
  t: Translate;
}

const I18nContext = createContext<I18nValue>({
  lang: 'fa',
  dir: 'rtl',
  t: (key) => key,
});

export function I18nProvider({ lang, children }: { lang: Language; children: ReactNode }) {
  const value = useMemo<I18nValue>(
    () => ({ lang, dir: lang === 'fa' ? 'rtl' : 'ltr', t: makeTranslate(lang) }),
    [lang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
